import { z } from "zod";
import { researchCostScenarios } from "trading-strategy-core/costs";
import type { MethodPoolStrategyRole } from "./method-pool-bindings";

/** Explicit file-import contract for the ten-position research artifacts.
 * Imported evidence is read-only: it never registers, promotes or enables a
 * strategy, and it is not a performance qualification. */
export const labPortfolioEvidenceMaxFileBytes = 8 * 1024 * 1024;
export const labPortfolioEvidenceMaxBatchBytes = 32 * 1024 * 1024;
export const labPortfolioEvidenceMaxFiles = 64;

/** Runners now emit the complete execution-dependency identity. Older
 * checkpoints keep the frozen identity-only format, so both stay readable. */
export const tenPositionRegistrationVersions = [
  "theory-study-ten-2",
  "theory-study-ten-3",
] as const;
export type TenPositionRegistrationVersion =
  (typeof tenPositionRegistrationVersions)[number];

/** Roles come from the centralized preset -> strategy binding table. The lab
 * receives them from the server and never imports a Node CLI module. */
export const labPortfolioCandidateRoles = [
  "entry-experiment",
  "source-exit",
  "proxy",
  "protected",
  "unbound",
] as const satisfies readonly MethodPoolStrategyRole[];
export type LabPortfolioCandidateRole =
  (typeof labPortfolioCandidateRoles)[number];

const digest = z.string().regex(/^[a-f0-9]{64}$/);
const market = z.enum(["cn-equity", "crypto"]);
const label = z.string().trim().min(1).max(150);
const date = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/)
  .refine((value) => {
    const parsed = Date.parse(`${value}T00:00:00Z`);
    return (
      Number.isFinite(parsed) &&
      new Date(parsed).toISOString().slice(0, 10) === value
    );
  }, "日期无效");

function uniqueLabels(
  values: readonly string[],
  path: (string | number)[],
  message: string,
  ctx: z.RefinementCtx,
) {
  if (new Set(values).size !== values.length)
    ctx.addIssue({ code: z.ZodIssueCode.custom, path, message });
}

export const tenPositionWindowSchema = z
  .object({
    label,
    start: date,
    end: date,
  })
  .strict();

/** The execution identity recorded by `researchExecutionIdentity()`. The
 * nested shape is strict: a missing dependency group or a non-hash value means
 * the file is not the real runner output. */
const dependencyHashSchema = z
  .object({
    path: z.string().min(1),
    hash: digest,
  })
  .strict();

export const researchExecutionIdentitySchema = z
  .object({
    runner: dependencyHashSchema,
    definitions: z.array(dependencyHashSchema),
    artifacts: z
      .object({
        roots: z.array(z.string().min(1)).min(1),
        hash: digest,
      })
      .strict(),
    lockfile: dependencyHashSchema,
  })
  .strict();

const registrationCore = {
  account: z
    .object({
      maxPositions: z.literal(10),
      targetWeight: z.literal(0.1),
    })
    .strict(),
  markets: z.array(market).min(1),
  windows: z.array(tenPositionWindowSchema).min(1),
  scenarios: z.array(z.enum(researchCostScenarios)).min(1),
  includeBaseline: z.boolean(),
  candidates: z.array(label).min(1),
};

function refineRegistration(
  value: {
    markets: string[];
    scenarios: string[];
    candidates: string[];
    windows: { label: string; start: string; end: string }[];
    includeBaseline: boolean;
  },
  ctx: z.RefinementCtx,
) {
  uniqueLabels(value.markets, ["markets"], "市场不能重复", ctx);
  uniqueLabels(value.scenarios, ["scenarios"], "成本情景不能重复", ctx);
  uniqueLabels(value.candidates, ["candidates"], "候选策略不能重复", ctx);
  uniqueLabels(
    value.windows.map((window) => window.label),
    ["windows"],
    "窗口标签不能重复",
    ctx,
  );
  if (value.includeBaseline && value.candidates.includes("baseline-hold"))
    ctx.addIssue({
      code: z.ZodIssueCode.custom,
      path: ["candidates"],
      message: "baseline-hold 不应同时出现在候选中",
    });
  value.windows.forEach((window, index) => {
    if (window.start > window.end)
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ["windows", index],
        message: "窗口开始日期不能晚于结束日期",
      });
  });
}

/** Registration bytes generated by either runner. Unknown fields are
 * preserved because the identity is the hash of the whole object. */
export const tenPositionRegistrationSchema = z
  .discriminatedUnion("version", [
    z
      .object({
        version: z.literal("theory-study-ten-2"),
        ...registrationCore,
      })
      .passthrough(),
    z
      .object({
        version: z.literal("theory-study-ten-3"),
        execution: researchExecutionIdentitySchema,
        ...registrationCore,
      })
      .passthrough(),
  ])
  .superRefine(refineRegistration);

export const tenPositionCheckpointKeySchema = z
  .object({
    market,
    strategyId: label,
    window: label,
    scenario: z.enum(researchCostScenarios),
  })
  .strict();

const completedRow = z
  .object({
    market,
    strategyId: label,
    window: label,
    scenario: z.enum(researchCostScenarios),
    status: z.literal("completed"),
    peakPositions: z.number().int().min(0).max(10),
    returnToDrawdown: z.number().finite().nullable(),
    meanExposure: z.number().finite().nullable(),
    netReturn: z.number().finite(),
    maxDrawdown: z.number().finite().min(0),
    buys: z.number().int().min(0),
    sells: z.number().int().min(0),
    turnoverNotional: z.number().finite().min(0),
    rejectionReasons: z.record(z.string().max(300), z.number().int().min(0)),
    fees: z.number().finite().min(0),
    rejections: z.number().int().min(0),
    observations: z.number().int().min(0),
    openPositions: z.number().int().min(0).max(10),
    quality: z.literal("rule-check-only"),
    fillsHash: digest,
    curveHash: digest,
  })
  .passthrough();

const blockedRow = z
  .object({
    market,
    strategyId: label,
    window: label,
    scenario: z.enum(researchCostScenarios),
    status: z.literal("blocked"),
    reason: z.string().trim().min(1).max(1000),
  })
  .strict();

/** A completed row must carry the engine summary; a blocked row must carry an
 * explicit reason. Unknown statuses are rejected instead of being guessed. */
export const tenPositionCheckpointRowSchema = z.discriminatedUnion("status", [
  completedRow,
  blockedRow,
]);

export const tenPositionCheckpointEnvelopeSchema = z
  .object({
    identity: digest,
    key: tenPositionCheckpointKeySchema,
    row: z.unknown(),
    contentHash: digest,
  })
  .strict();

export const labPortfolioEvidenceFileSchema = z
  .object({
    name: z.string().min(1).max(300),
    content: z
      .string()
      .max(labPortfolioEvidenceMaxFileBytes, "文件超过 8 MiB 限制"),
  })
  .strict();

export const labPortfolioEvidenceImportSchema = z
  .object({
    files: z
      .array(labPortfolioEvidenceFileSchema)
      .min(1)
      .max(labPortfolioEvidenceMaxFiles),
  })
  .strict();

export const labPortfolioEvidenceHashSchema = z
  .object({ hash: digest })
  .strict();

export type TenPositionRegistration = z.infer<
  typeof tenPositionRegistrationSchema
>;
export type TenPositionCheckpointKey = z.infer<
  typeof tenPositionCheckpointKeySchema
>;
export type TenPositionCheckpointRow = z.infer<
  typeof tenPositionCheckpointRowSchema
>;
export type LabPortfolioEvidenceImport = z.infer<
  typeof labPortfolioEvidenceImportSchema
>;
