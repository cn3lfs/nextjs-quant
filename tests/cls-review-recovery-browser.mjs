import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { homedir, tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
const { chromium } = createRequire(join(homedir(), ".agent-tools/playwright/package.json"))("playwright");
const directory=resolve(process.env.QUANT_DATA_DIR??"");
assert.ok(directory.startsWith(resolve(tmpdir())+"\\quant-cls-review-"));
const path=join(directory,"CLS-ui-import.md"),logs=join(tmpdir(),"logs/quant-cls-review");
const first="# 隔离导入版本一\n报告日期：2026-09-29\n### 行业观点\n只读原文。\n";
const second=first.replace("版本一","版本二");
writeFileSync(path,first);
const browser=await chromium.launch({channel:"chrome",headless:true});
const checks=[],errors=[];
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on("pageerror",error=>errors.push(error.message));
  await page.goto("http://127.0.0.1:3224/cls-review");
  await page.getByRole("button",{name:"导入报告",exact:true}).click();
  await page.getByLabel("报告文件完整路径",{exact:true}).fill(path);
  await page.getByRole("button",{name:"预览报告",exact:true}).click();
  await page.getByText("隔离导入版本一",{exact:true}).waitFor();
  await page.getByLabel("报告文件完整路径",{exact:true}).fill(path+"-changed.md");
  assert.ok(await page.getByRole("button",{name:"导入此版本",exact:true}).isDisabled());
  await page.getByLabel("报告文件完整路径",{exact:true}).fill(path);
  writeFileSync(path,second);
  await page.getByRole("button",{name:"导入此版本",exact:true}).click();
  await page.getByRole("alert").filter({hasText:"报告已变化"}).waitFor();
  await page.getByRole("button",{name:"预览报告",exact:true}).click();
  await page.getByText("隔离导入版本二",{exact:true}).waitFor();
  await page.getByRole("button",{name:"导入此版本",exact:true}).click();
  await page.getByRole("heading",{name:"隔离导入版本二",exact:true}).waitFor();
  checks.push("path drift disables import; on-disk hash drift rejected; new preview imports correct version");
  await page.getByRole("button",{name:"报告信息",exact:true}).click();
  await page.evaluate(()=>{const original=URL.createObjectURL;URL.createObjectURL=()=>{URL.createObjectURL=original;throw new Error("synthetic export failure");};});
  await page.getByRole("button",{name:"导出报告与全部关联复盘",exact:true}).click();
  await page.getByRole("alert").filter({hasText:"synthetic export failure"}).waitFor();
  const downloadPromise=page.waitForEvent("download");
  await page.getByRole("button",{name:"导出报告与全部关联复盘",exact:true}).click();
  const download=await downloadPromise;
  const exported=JSON.parse(readFileSync(await download.path(),"utf8"));
  assert.equal(exported.report.report.markdown,second);
  assert.equal(await page.getByRole("alert").filter({hasText:"synthetic export failure"}).count(),0);
  checks.push("failed export retries with complete source and clears stale error");
  await page.getByRole("button",{name:"清理此版本",exact:true}).click();
  const dialog=page.getByRole("dialog",{name:"清理报告版本",exact:true});
  await dialog.getByRole("button",{name:"保留",exact:true}).click();
  await page.getByRole("button",{name:"清理此版本",exact:true}).click();
  await dialog.getByRole("button",{name:"确认清理报告及关联证据",exact:true}).click();
  await page.getByText("此版本及关联证据已清理，样本日期占位保留，不能重新选样。",{exact:true}).waitFor();
  assert.equal(readFileSync(path,"utf8"),second);
  checks.push("clear confirmation can cancel; clear removes archive, source file unchanged");
  await page.goto("http://127.0.0.1:3224/cls-review?clsReport=missing-report");
  await page.getByText("报告不存在或已清理，请返回列表重新选择。",{exact:true}).waitFor();
  await page.getByRole("button",{name:"返回报告列表",exact:true}).click();
  assert.equal(await page.evaluate(()=>document.activeElement?.id),"cls-report-title");
  await page.goto("http://127.0.0.1:3224/cls-review?clsReport=cls-review-report%3Afixture-00999&clsTab=facts");
  await page.getByRole("heading",{name:"合成报告 999",exact:true}).waitFor();
  const section=page.getByRole("combobox",{name:"原文章节",exact:true});
  await section.focus();await page.keyboard.press("Space");await page.keyboard.press("Home");await page.keyboard.press("Enter");
  assert.match(await section.innerText(),/行业观点/);
  await page.screenshot({path:join(logs,"final-1440.png"),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.getByRole("region",{name:"已导入报告",exact:true}).isVisible(),false);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:join(logs,"final-390.png"),fullPage:true});
  await page.getByRole("button",{name:"返回报告列表",exact:true}).click();
  assert.ok(await page.getByRole("region",{name:"已导入报告",exact:true}).isVisible());
  checks.push("missing ID recovery, direct URL, keyboard selection and narrow-screen return/focus");
  assert.deepEqual(errors,[]);
  writeFileSync(join(logs,"recovery.json"),JSON.stringify({checks,errors},null,2));
  console.log(JSON.stringify(checks));
}catch(error){const page=browser.contexts()[0]?.pages()[0];if(page){writeFileSync(join(logs,"recovery-failure.txt"),await page.locator("body").innerText());await page.screenshot({path:join(logs,"recovery-failure.png"),fullPage:true});}throw error;}
finally{await browser.close();}
